# Capcraft — a Minecraft-style proportional pixel font for the hackgt-26 HUD.
# Grid: 8 rows per glyph. Rows 0-6 sit on/above the baseline (row 6 is the
# baseline row, cap height = 7), row 7 is the single descender row.
# Glyphs marked (extracted) were read pixel-for-pixel off the reference
# subtitle screenshot; everything else is drawn to match that style
# (1px stems, 5px default width, middle bar on row 2, 1px letter spacing).

G = {}

def g(ch, *rows):
    rows = list(rows)
    while len(rows) < 8:
        rows.append('.' * len(rows[0]))
    w = len(rows[0])
    assert all(len(r) == w for r in rows), (ch, rows)
    G[ch] = rows

